// Jobs, groups and office addresses are loaded once from public/data/data.json
// (generated by npm run crawl && npm run classify), with their translations (lib/i18n.js).
const JobsContext = createContext(null);

// `jobs` holds the open jobs every list shows; `allJobs` also has the closed ones, so their
// pages still open from old links. The search text holds both languages, so a keyword matches
// whichever language the visitor types in.
function prepare(data, other) {
  const groups = data.groups || {};
  const otherById = new Map((other.jobs || []).map((j) => [j.id, j]));
  const textOf = (j) => [j.desc, j.salary, j.location, locationText(j.location, 'en')];
  const allJobs = (data.jobs || []).map((j) => {
    const job = { stack: [], keywords: '', hot: false, ...j };
    const alt = otherById.get(job.id);
    job.searchText = norm([job.title, job.keywords, job.stack.join(' '), job.level,
      groups[job.group] ? groups[job.group].label : '', ...textOf(job), ...(alt ? textOf(alt) : [])].join(' '));
    return job;
  });
  return { groups, jobs: allJobs.filter((j) => !j.closed), allJobs, offices: data.offices || {} };
}

// Both languages of the jobs data, from the raw files.
function prepareBoth({ data, vi, en }) {
  const dataVi = withVietnamese(data, vi);
  const dataEn = withEnglish(data, en);
  return { vi: prepare(dataVi, dataEn), en: prepare(dataEn, dataVi) };
}

// No cache option: the host already serves the files with must-revalidate, and a plain request
// can reuse the <link rel="preload"> the prerendered pages carry.
function fetchData(file) {
  return fetch(import.meta.env.BASE_URL + 'data/' + file).then((res) => {
    if (!res.ok) throw new Error('HTTP ' + res.status);
    return res.json();
  });
}

// The raw files: data.json and its translations. Without a translations file the posts still
// show, as written.
export function loadJobsData() {
  return Promise.all([
    fetchData('data.json'),
    fetchData('data.vi.json').catch(() => null),
    fetchData('data.en.json').catch(() => null)
  ]).then(([data, vi, en]) => ({ data, vi, en }));
}

// `initialData` (loadJobsData's result) is given when prerendering and when hydrating a
// prerendered page, so the first render already has the jobs; otherwise they're fetched.
export function JobsProvider({ initialData, children }) {
  const { lang } = useLang();
  const [state, setState] = useState(() => (
    initialData ? { status: 'ready', both: prepareBoth(initialData) } : { status: 'loading', both: null }
  ));

  useEffect(() => {
    if (initialData) return undefined;
    let alive = true;
    loadJobsData()
      .then((raw) => alive && setState({ status: 'ready', both: prepareBoth(raw) }))
      .catch(() => alive && setState({ status: 'error', both: null }));
    return () => { alive = false; };
  }, [initialData]);

  const value = useMemo(() => ({ status: state.status, data: state.both && state.both[lang] }), [state, lang]);
  return <JobsContext.Provider value={value}>{children}</JobsContext.Provider>;
}

export function useJobs() {
  return useContext(JobsContext);
}

export function LoadState({ status }) {
  const { L } = useLang();
  if (status === 'error') {
    return <div className="load-state load-state--error" role="alert">{L('Không tải được danh sách việc làm. Vui lòng tải lại trang.', 'Couldn’t load the job list. Please reload the page.')}</div>;
  }
  return <div className="load-state" aria-busy="true">{L('Đang tải danh sách việc làm…', 'Loading jobs…')}</div>;
}
