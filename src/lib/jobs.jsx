// Jobs, groups and office addresses are loaded once from public/data/data.json
// (generated by npm run crawl && npm run classify).
const JobsContext = createContext(null);

// `jobs` holds the open jobs every list shows; `allJobs` also has the closed ones, so their
// pages still open from old links.
function prepare(data) {
  const groups = data.groups || {};
  const allJobs = (data.jobs || []).map((j) => {
    const job = { stack: [], keywords: '', hot: false, ...j };
    job.searchText = norm([job.title, job.desc, job.keywords, job.stack.join(' '),
      groups[job.group] ? groups[job.group].label : '', job.level, job.location].join(' '));
    return job;
  });
  return { groups, jobs: allJobs.filter((j) => !j.closed), allJobs, offices: data.offices || {} };
}

// No cache option: the host already serves it with must-revalidate, and a plain request can
// reuse the <link rel="preload"> the prerendered pages carry.
export function loadJobsData() {
  return fetch(import.meta.env.BASE_URL + 'data/data.json').then((res) => {
    if (!res.ok) throw new Error('HTTP ' + res.status);
    return res.json();
  });
}

// `initialData` (the raw data.json) is given when prerendering and when hydrating a
// prerendered page, so the first render already has the jobs; otherwise they're fetched.
export function JobsProvider({ initialData, children }) {
  const [state, setState] = useState(() => (
    initialData ? { status: 'ready', data: prepare(initialData) } : { status: 'loading', data: null }
  ));

  useEffect(() => {
    if (initialData) return undefined;
    let alive = true;
    loadJobsData()
      .then((json) => alive && setState({ status: 'ready', data: prepare(json) }))
      .catch(() => alive && setState({ status: 'error', data: null }));
    return () => { alive = false; };
  }, [initialData]);

  return <JobsContext.Provider value={state}>{children}</JobsContext.Provider>;
}

export function useJobs() {
  return useContext(JobsContext);
}

export function LoadState({ status }) {
  if (status === 'error') {
    return <div className="load-state load-state--error" role="alert">Không tải được danh sách việc làm. Vui lòng tải lại trang.</div>;
  }
  return <div className="load-state" aria-busy="true">Đang tải danh sách việc làm…</div>;
}
