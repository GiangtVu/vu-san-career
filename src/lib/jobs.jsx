import { createContext, useContext, useEffect, useState } from 'react';

// Lowercase and strip Vietnamese diacritics so "phân tích" matches "phan tich".
export function norm(t) {
  return String(t).toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd');
}

// "30/11/2026" -> "20261130", sortable as a string.
export function dateKey(d) {
  return d.split('/').reverse().join('');
}

export function parseDate(d) {
  const [day, month, year] = d.split('/').map(Number);
  return new Date(year, month - 1, day);
}

export function hotFirst(list) {
  return list.slice().sort((a, b) => (b.hot ? 1 : 0) - (a.hot ? 1 : 0));
}

// A job hiring in several places has a location like "Hà Nội / TP. HCM".
export function placesOf(job) {
  return job.location.split(' / ');
}

const PLACE_LABELS = { 'TP. HCM': 'TP. Hồ Chí Minh' };

export function placeLabel(place) {
  return PLACE_LABELS[place] || place;
}

// Every technology a post asks for; `stack` is the short list shown on cards.
export function skillsOf(job) {
  return (job.detail && job.detail.skills) || job.stack;
}

export function matches(job, q) {
  return !q || job.searchText.includes(q);
}

export function jobPath(id) {
  return '/viec-lam/' + encodeURIComponent(id);
}

// Job list URL carrying the current keyword and group, read back by the list page.
export function listPath(q, group) {
  const params = new URLSearchParams();
  if (q && q.trim()) params.set('q', q.trim());
  if (group) params.set('group', group);
  const query = params.toString();
  return '/viec-lam' + (query ? '?' + query : '');
}

// Job list filtered to posts asking for one exact skill. Unlike the keyword search,
// "Java" here doesn't also match "JavaScript".
export function skillPath(skill) {
  return '/viec-lam?skill=' + encodeURIComponent(skill);
}

